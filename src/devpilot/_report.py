"""Render report.html and ONBOARDING.md from facts/findings/verify JSON."""
from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

from jinja2 import Environment, FileSystemLoader

_SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2}


def _load_json(path: Path, default):
    """Load JSON from *path*, returning *default* if the file does not exist."""
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def _build_mermaid(languages: list[dict]) -> str:
    """Build a simple Mermaid graph LR from language names."""
    names = [lang["name"] for lang in languages if lang.get("name")]
    if not names:
        return "graph LR\n  (no languages detected)"
    if len(names) == 1:
        return f"graph LR\n  {names[0]}"
    # Connect first language to every other language
    root = names[0]
    lines = ["graph LR"]
    for other in names[1:]:
        # Sanitize node IDs (spaces → underscores)
        root_id = root.replace(" ", "_").replace("-", "_")
        other_id = other.replace(" ", "_").replace("-", "_")
        lines.append(f"  {root_id}[\"{root}\"] --> {other_id}[\"{other}\"]")
    return "\n".join(lines)


def _first_tasks(todos: list[dict], hotspots: list[dict], top_n: int = 5) -> list[dict]:
    """Return up to *top_n* best starter TODOs ranked by score."""
    hotspot_paths = {h.get("path", "") for h in hotspots}
    scored = []
    for t in todos:
        text = t.get("text", "")
        file_ = t.get("file", "")
        score = 1.0 / max(1, len(text))
        # Add 1.0 bonus if the file is NOT a hotspot (easier/safer starting point)
        if not any(file_ == hp or file_.endswith(hp) or hp.endswith(file_) for hp in hotspot_paths):
            score += 1.0
        scored.append((score, t))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [t for _, t in scored[:top_n]]


def _write_onboarding_md(
    out_dir: Path,
    facts: dict,
    setup_steps: list[dict],
    findings: list[dict],
    first_tasks: list[dict],
    report_generated_at: str,
) -> Path:
    """Write a skeleton ONBOARDING.md and return its path."""
    lines: list[str] = []

    repo = facts.get("repo", "unknown")
    lines += [f"# {repo} — Onboarding Guide", ""]
    lines += [f"_Generated by DevPilot on {report_generated_at}_", ""]

    # Setup
    lines += ["## Setup", ""]
    if setup_steps:
        for step in setup_steps:
            lines.append(f"- `{step['command']}`")
    else:
        lines.append("_No verified setup steps. Run `devpilot verify` first._")
    lines.append("")

    # Environment Variables
    lines += ["## Environment Variables", ""]
    env_vars = facts.get("env_vars", [])
    if env_vars:
        for ev in env_vars:
            lines.append(f"- `{ev.get('name', '')}`")
    else:
        lines.append("_No environment variables detected._")
    lines.append("")

    # Owners
    lines += ["## Owners", ""]
    owners = facts.get("owners", [])
    if owners:
        for o in owners:
            owner_list = ", ".join(o.get("owners", []))
            lines.append(f"- `{o.get('path', '')}` — {owner_list}")
    else:
        lines.append("_No owner information found._")
    lines.append("")

    # Drift Findings
    lines += ["## Drift Findings", ""]
    if findings:
        for f in findings:
            lines.append(f"- **[{f.get('id', '')}]** `{f.get('severity', '')}` — {f.get('message', '')}")
    else:
        lines.append("_No drift findings._")
    lines.append("")

    # First Tasks
    lines += ["## Suggested First Tasks", ""]
    if first_tasks:
        for t in first_tasks:
            lines.append(f"1. `{t.get('file', '')}:{t.get('line', '')}` — {t.get('text', '')}")
    else:
        lines.append("_No TODO/FIXME candidates found._")
    lines.append("")

    md_path = out_dir / "ONBOARDING.md"
    md_path.write_text("\n".join(lines), encoding="utf-8")
    return md_path


def render_report(repo: Path, out_dir: Path) -> tuple[Path, Path]:
    """Render report.html and ONBOARDING.md from facts/findings/verify JSON.

    Returns (html_path, md_path).
    """
    # 1. Load inputs
    facts: dict = _load_json(out_dir / "facts.json", {})
    findings_raw: list = _load_json(out_dir / "findings.json", [])
    verify_raw: list = _load_json(out_dir / "verify.json", [])

    # 2. Sort findings by severity
    findings = sorted(
        findings_raw,
        key=lambda f: _SEVERITY_ORDER.get(f.get("severity", "low"), 2),
    )

    # 3. Compute template context
    languages = facts.get("languages", [])
    deps = facts.get("deps")
    owners = facts.get("owners", [])
    todos_all: list[dict] = facts.get("todos", [])[:50]
    hotspots: list[dict] = facts.get("hotspots", [])[:20]

    verify_steps: list[dict] = verify_raw
    setup_steps = [s for s in verify_steps if s.get("passed") is True]

    ranked_first_tasks = _first_tasks(todos_all, hotspots)
    mermaid_diagram = _build_mermaid(languages)
    report_generated_at = datetime.now(UTC).isoformat()

    context = {
        "facts": facts,
        "languages": languages,
        "deps": deps,
        "findings": findings,
        "verify_steps": verify_steps,
        "setup_steps": setup_steps,
        "owners": owners,
        "todos": todos_all,
        "hotspots": hotspots,
        "first_tasks": ranked_first_tasks,
        "mermaid_diagram": mermaid_diagram,
        "report_generated_at": report_generated_at,
    }

    # 4. Render HTML via Jinja2
    templates_dir = Path(__file__).parent / "report" / "templates"
    env = Environment(loader=FileSystemLoader(str(templates_dir)), autoescape=False)
    template = env.get_template("report.html.j2")
    html_content = template.render(**context)

    # 5. Write outputs
    html_path = out_dir / "report.html"
    html_path.write_text(html_content, encoding="utf-8")

    md_path = _write_onboarding_md(
        out_dir=out_dir,
        facts=facts,
        setup_steps=setup_steps,
        findings=findings,
        first_tasks=ranked_first_tasks,
        report_generated_at=report_generated_at,
    )

    return html_path, md_path
